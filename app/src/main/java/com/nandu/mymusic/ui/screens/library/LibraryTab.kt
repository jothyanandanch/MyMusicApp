/**
 * Apple Music "Library" tab — mode switcher, playlists shelf (with pinned
 * Liked Songs), and the song list. Absorbs the old playlist tab's main list.
 */
@Composable
fun LibraryTab(
    viewModel: MusicViewModel,
    songs: List<Song>,
    currentSong: Song?,
    favoriteIds: Set<Long>,
    playlists: Map<String, List<Long>>,
    autoGeneratedPlaylists: Set<String>,
    libraryMode: Int,
    isDataSaverMode: Boolean,
    hybridLocalOnly: Boolean,
    hybridOnlineOnly: Boolean,
    onHybridLocalOnly: (Boolean) -> Unit,
    onHybridOnlineOnly: (Boolean) -> Unit,
    sortType: SortType,
    onSortChange: (SortType) -> Unit,
    showSnackbar: (String) -> Unit,
    onSongClick: (Song) -> Unit,
    onToggleFavorite: (Song) -> Unit,
    onShuffleAll: () -> Unit,
    onAddToPlaylist: (Song) -> Unit,
    onAddSongsToPlaylist: (List<Song>) -> Unit,
    onViewAlbum: (String) -> Unit,
    onViewArtist: (String) -> Unit,
    onDownload: (Song) -> Unit,
    onOpenLikedSongs: () -> Unit,
    onOpenPlaylist: (String) -> Unit,
    onOpenMainPlaylist: (String) -> Unit
) {
    val C = appleColors()
    val context = LocalContext.current
    val mainPlaylistName = if (libraryMode == 0) "Local" else "All Songs"

    // Language settings dialog
    var showLanguageSettings by remember { mutableStateOf(false) }
    val optionalLangs = listOf("Hindi", "Tamil", "Malayalam")

    // Create playlist dialog
    var showCreateDialog by remember { mutableStateOf(false) }
    var newPlaylistName by remember { mutableStateOf("") }

    // Add-songs overlay
    var playlistToAddSongsTo by remember { mutableStateOf<String?>(null) }

    // Import playlist launcher (JSON exported by this app)
    val importLauncher = rememberLauncherForActivityResult(ActivityResultContracts.OpenDocument()) { uri ->
        if (uri != null) {
            try {
                val text = context.contentResolver.openInputStream(uri)?.bufferedReader()?.use { it.readText() }
                val parsed = text?.let { parsePlaylistImportJson(it) }
                if (parsed == null || parsed.entries.isEmpty()) {
                    showSnackbar("Couldn't read that playlist file")
                } else {
                    val matched = parsed.entries.mapNotNull { entry ->
                        songs.firstOrNull {
                            it.title.trim().equals(entry.title.trim(), ignoreCase = true) &&
                                it.artist.trim().equals(entry.artist.trim(), ignoreCase = true)
                        }
                    }
                    var finalName = parsed.name.ifBlank { "Imported Playlist" }
                    var counter = 2
                    while (playlists.containsKey(finalName)) {
                        finalName = "${parsed.name.ifBlank { "Imported Playlist" }} ($counter)"
                        counter++
                    }
                    viewModel.createPlaylist(finalName)
                    if (matched.isNotEmpty()) viewModel.addSongsToPlaylist(finalName, matched)
                    showSnackbar("Imported \"$finalName\" — matched ${matched.size} of ${parsed.entries.size} songs")
                }
            } catch (e: Exception) {
                showSnackbar("Import failed")
            }
        }
    }

    // Sorting pipeline (same as the old Home tab)
    val displaySongs = remember(songs, sortType) {
        when (sortType) {
            SortType.DEFAULT -> songs
            SortType.TITLE_AZ -> songs.sortedBy { it.title?.lowercase() ?: "" }
            SortType.TITLE_ZA -> songs.sortedByDescending { it.title?.lowercase() ?: "" }
            SortType.ARTIST -> songs.sortedBy { it.artist?.lowercase() ?: "" }
        }
    }

    val (autoPlaylists, userPlaylists) = remember(playlists, autoGeneratedPlaylists) {
        playlists.entries.toList().partition { autoGeneratedPlaylists.contains(it.key) }
    }
    val sortedAutoPlaylists = autoPlaylists.sortedBy {
        when (it.key) { "Telugu Songs" -> 0; "English Songs" -> 1; else -> 2 }
    }

    if (playlistToAddSongsTo != null) {
        val pName = playlistToAddSongsTo!!
        val existingIds = playlists[pName] ?: emptyList()
        AddSongsScreen(
            playlistName = pName,
            availableSongs = songs.filter { !existingIds.contains(it.id) },
            onDismiss = { playlistToAddSongsTo = null },
            onAddSongs = { selectedSongs ->
                viewModel.addSongsToPlaylist(pName, selectedSongs)
                showSnackbar("Added ${selectedSongs.size} songs to $pName")
                playlistToAddSongsTo = null
            }
        )
        return
    }

    LazyColumn(
        modifier = Modifier
            .fillMaxSize()
            .background(C.background)
            .statusBarsPadding(),
        contentPadding = PaddingValues(bottom = 24.dp)
    ) {
        item { LargeTitleHeader("Library") }

        item {
            ModeSwitcher(
                libraryMode = libraryMode,
                onModeChange = { viewModel.setLibraryMode(it) },
                isDataSaverMode = isDataSaverMode,
                onDataSaverChange = { viewModel.setDataSaverMode(it) },
                hybridLocalOnly = hybridLocalOnly,
                hybridOnlineOnly = hybridOnlineOnly,
                onHybridLocalOnly = onHybridLocalOnly,
                onHybridOnlineOnly = onHybridOnlineOnly
            )
        }

        // ── Playlists shelf ──
        item {
            SectionHeader("Playlists")
            LazyRow(
                contentPadding = PaddingValues(horizontal = 16.dp),
                horizontalArrangement = Arrangement.spacedBy(4.dp)
            ) {
                item(key = "liked") {
                    PlaylistShelfCard(
                        name = "Liked Songs",
                        songCount = favoriteIds.size,
                        gradient = LikedSongsGradient,
                        icon = Icons.Filled.Favorite,
                        onClick = onOpenLikedSongs
                    )
                }
                item(key = "main") {
                    PlaylistShelfCard(
                        name = mainPlaylistName,
                        songCount = songs.size,
                        icon = Icons.Filled.MusicNote,
                        onClick = { onOpenMainPlaylist(mainPlaylistName) }
                    )
                }
                items(sortedAutoPlaylists, key = { "auto_${it.key}" }) { (name, ids) ->
                    PlaylistShelfCard(name = name, songCount = ids.size, onClick = { onOpenPlaylist(name) })
                }
                items(userPlaylists, key = { "user_${it.key}" }) { (name, ids) ->
                    PlaylistShelfCard(name = name, songCount = ids.size, onClick = { onOpenPlaylist(name) })
                }
            }
        }

        // ── Playlist management icons ──
        item {
            Row(
                modifier = Modifier.fillMaxWidth().padding(horizontal = 16.dp, vertical = 4.dp),
                horizontalArrangement = Arrangement.End
            ) {
                IconButton(onClick = { importLauncher.launch(arrayOf("application/json")) }) {
                    Icon(Icons.Filled.FileUpload, "Import Playlist", tint = C.secondaryLabel)
                }
                IconButton(onClick = { showLanguageSettings = true }) {
                    Icon(Icons.Filled.Settings, "Language Settings", tint = C.secondaryLabel)
                }
                IconButton(onClick = { showCreateDialog = true }) {
                    Icon(Icons.Filled.Add, "Create Playlist", tint = C.secondaryLabel)
                }
            }
        }

        // ── Songs section ──
        item {
            Row(
                modifier = Modifier.fillMaxWidth().padding(start = 20.dp, end = 12.dp, top = 12.dp, bottom = 4.dp),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                Text("Songs", style = com.nandu.mymusic.ui.theme.AppleText.Title2, color = C.label)
                Row(verticalAlignment = Alignment.CenterVertically) {
                    SortMenu(sortType = sortType, onSortChange = onSortChange)
                    IconButton(onClick = onShuffleAll) {
                        Icon(Icons.Filled.Shuffle, "Shuffle All", tint = C.accent, modifier = Modifier.size(22.dp))
                    }
                }
            }
        }

        items(displaySongs, key = { it.id }) { song ->
            SongItem(
                song = song, currentSong = currentSong, isFavorite = favoriteIds.contains(song.id),
                onSongClick = { onSongClick(song) }, onToggleFavorite = { onToggleFavorite(song) },
                onPlayNext = { viewModel.setPlayNext(song); showSnackbar("Will play next") },
                onAddToQueue = { viewModel.addToQueue(song); showSnackbar("Added to queue") },
                onAddToPlaylist = { onAddToPlaylist(song) },
                onDelete = { viewModel.deleteSong(song); },
                onEdit = { showSnackbar("Edit functionality coming soon!") },
                onDownload = { onDownload(song) },
                onViewAlbum = { onViewAlbum(song.album ?: "Unknown Album") },
                onViewArtist = { onViewArtist(song.artist ?: "Unknown Artist") }
            )
        }
    }

    // ── Language settings dialog ──
    if (showLanguageSettings) {
        val enabledLangs = viewModel.enabledLanguages
        androidx.compose.material3.AlertDialog(
            onDismissRequest = { showLanguageSettings = false },
            containerColor = C.cardElevated,
            title = { Text("Auto-Generated Playlists", color = C.label, fontWeight = androidx.compose.ui.text.font.FontWeight.Bold) },
            text = {
                Column {
                    Text("Telugu and English are always generated automatically.", color = C.secondaryLabel, fontSize = 13.sp)
                    Spacer(Modifier.height(16.dp))
                    Text("Optional Languages:", color = C.label, fontWeight = androidx.compose.ui.text.font.FontWeight.SemiBold)
                    Spacer(Modifier.height(8.dp))

                    optionalLangs.forEach { lang ->
                        var isChecked by remember { mutableStateOf(enabledLangs.contains(lang)) }
                        Row(
                            verticalAlignment = Alignment.CenterVertically,
                            modifier = Modifier
                                .fillMaxWidth()
                                .clickable {
                                    isChecked = !isChecked
                                    viewModel.toggleLanguagePlaylist(lang, isChecked)
                                }
                                .padding(vertical = 4.dp)
                        ) {
                            androidx.compose.material3.Checkbox(
                                checked = isChecked,
                                onCheckedChange = {
                                    isChecked = it
                                    viewModel.toggleLanguagePlaylist(lang, it)
                                },
                                colors = androidx.compose.material3.CheckboxDefaults.colors(
                                    checkedColor = C.accent,
                                    uncheckedColor = C.secondaryLabel
                                )
                            )
                            Text(lang, color = C.label)
                        }
                    }
                }
            },
            confirmButton = {
                androidx.compose.material3.TextButton(onClick = { showLanguageSettings = false }) {
                    Text("Done", color = C.accent, fontWeight = androidx.compose.ui.text.font.FontWeight.Bold)
                }
            }
        )
    }
}
