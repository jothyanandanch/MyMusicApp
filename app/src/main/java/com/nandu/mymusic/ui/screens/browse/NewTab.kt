/** All languages the app can generate playlists for — the Browse grid always shows these. */
private val SupportedLanguages = listOf("Telugu", "English", "Hindi", "Tamil", "Malayalam")

/**
 * Apple Music "New" (Browse) tab — shelves from the online catalog plus a
 * colorful category grid. Pull-to-refresh refreshes the online library.
 */
@OptIn(androidx.compose.material3.ExperimentalMaterial3Api::class)
@Composable
fun NewTab(
    allOnlineSongs: List<Song>,
    hotTracks: List<Song>,
    isRefreshing: Boolean,
    onRefresh: () -> Unit,
    currentSong: Song?,
    autoGeneratedPlaylists: Set<String>,
    isLoading: Boolean,
    rotationSeed: Int,
    onSongClick: (Song, List<Song>) -> Unit,
    onOpenPlaylist: (String) -> Unit,
    onOpenLikedSongs: () -> Unit
) {
    val C = appleColors()
    var selectedCategory by remember { mutableStateOf<String?>(null) }

    // New Music: a rotating editorial-style selection — different picks each
    // app launch (like Apple's refreshed New page) instead of a fixed list.
    val newMusic = remember(allOnlineSongs, rotationSeed) {
        if (allOnlineSongs.size <= 12) allOnlineSongs
        else allOnlineSongs.shuffled(kotlin.random.Random(rotationSeed)).take(12)
    }

    // Hot Tracks: ranked most-played (from the ViewModel's persistent play
    // counts). Until counts build up, fall back to catalog order so the
    // section is never empty.
    val rankedTracks = if (hotTracks.isNotEmpty()) hotTracks else allOnlineSongs
    val hotList = remember(rankedTracks) { rankedTracks.take(10) }

    PullToRefreshBox(
        isRefreshing = isRefreshing,
        onRefresh = onRefresh,
        modifier = Modifier.fillMaxSize().background(C.background)
    ) {
        LazyColumn(
            modifier = Modifier
                .fillMaxSize()
                .statusBarsPadding(),
            contentPadding = PaddingValues(bottom = 24.dp)
        ) {
            item { LargeTitleHeader("New") }

            if (selectedCategory != null) {
                // ── Category drill-in: songs of the chosen language ──
                val category = selectedCategory!!
                val categorySongs = allOnlineSongs.filter {
                    it.language?.equals(category, ignoreCase = true) == true
                }
                item {
                    Row(
                        modifier = Modifier.fillMaxWidth().padding(horizontal = 8.dp, vertical = 4.dp),
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        IconButton(onClick = { selectedCategory = null }) {
                            Icon(Icons.Filled.Close, "Close category", tint = C.accent)
                        }
                        Text(category, style = AppleText.Title2, color = C.label)
                    }
                }
                if (categorySongs.isEmpty()) {
                    item {
                        Column(
                            modifier = Modifier.fillMaxWidth().padding(top = 72.dp),
                            horizontalAlignment = Alignment.CenterHorizontally
                        ) {
                            Text("No songs in this category yet", color = C.label, fontWeight = FontWeight.SemiBold, fontSize = 16.sp)
                            Text("Check back after the catalog refreshes", color = C.secondaryLabel, fontSize = 13.sp)
                        }
                    }
                } else {
                    items(categorySongs, key = { "cat_${it.id}" }) { song ->
                        SongItem(
                            song = song, currentSong = currentSong, isFavorite = false,
                            onSongClick = { onSongClick(song, categorySongs) },
                            onToggleFavorite = {},
                        )
                    }
                }
            } else {
                // ── New Music shelf ──
                if (allOnlineSongs.isNotEmpty()) {
                    item {
                        Section("New Music") {
                            items(newMusic, key = { "new_${it.id}" }) { song ->
                                SongShelfCard(song = song, onClick = { onSongClick(song, allOnlineSongs) })
                            }
                        }
                    }
                }

                // ── Browse Categories (2-column gradient grid) ──
                item {
                    // Languages that actually have songs rank first, then the
                    // remaining supported languages — the grid is always full.
                    val songLanguages = allOnlineSongs
                        .mapNotNull { it.language?.takeIf { l -> l.isNotBlank() && !l.equals("Unknown", true) } }
                        .distinct()
                    val languages = (songLanguages + SupportedLanguages).distinct()
                    val tileCount = languages.size + 1 // + Liked Songs tile
                    val rows = (tileCount + 1) / 2

                    SectionHeader("Browse Categories")
                    LazyVerticalGrid(
                        columns = GridCells.Fixed(2),
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(horizontal = 16.dp)
                            .height((110.dp * rows) + (12.dp * (rows - 1))),
                        horizontalArrangement = Arrangement.spacedBy(12.dp),
                        verticalArrangement = Arrangement.spacedBy(12.dp),
                        userScrollEnabled = false
                    ) {
                        itemsIndexed(languages) { index, language ->
                            val gradient = CategoryGradients[index % CategoryGradients.size]
                            CategoryTile(
                                label = language,
                                gradient = gradient,
                                onClick = {
                                    // Prefer the real language playlist when it exists
                                    if (autoGeneratedPlaylists.contains("${language} Songs")) {
                                        selectedCategory = null
                                        onOpenPlaylist("${language} Songs")
                                    } else {
                                        selectedCategory = language
                                    }
                                }
                            )
                        }
                        item {
                            CategoryTile(
                                label = "Liked Songs",
                                gradient = LikedSongsGradient,
                                icon = Icons.Filled.Favorite,
                                onClick = {
                                    selectedCategory = null
                                    onOpenLikedSongs()
                                }
                            )
                        }
                    }
                }

                // ── Hot Tracks list (most-played, ranked by play count) ──
                if (rankedTracks.isNotEmpty()) {
                    item {
                        SectionHeader("Hot Tracks")
                        hotList.forEachIndexed { index, song ->
                            SongItem(
                                song = song, currentSong = currentSong, isFavorite = false,
                                onSongClick = { onSongClick(song, rankedTracks) },
                                onToggleFavorite = {},
                                showTrackNumber = true,
                                trackNumber = index + 1
                            )
                        }
                    }
                } else {
                    item {
                        Column(
                            modifier = Modifier.fillMaxWidth().padding(top = 48.dp),
                            horizontalAlignment = Alignment.CenterHorizontally
                        ) {
                            Icon(Icons.Filled.CloudOff, null, tint = C.secondaryLabel, modifier = Modifier.size(64.dp))
                            Spacer(Modifier.height(16.dp))
                            Text("No online songs found", color = C.label, fontSize = 20.sp, fontWeight = FontWeight.Bold)
                            Text("Pull down to refresh or check your connection", color = C.secondaryLabel)
                        }
                    }
                }
            }
        }
    }
}

@Composable
private fun CategoryTile(
    label: String,
    gradient: List<Color>,
    onClick: () -> Unit,
    icon: androidx.compose.ui.graphics.vector.ImageVector? = null
) {
    Box(
        modifier = Modifier
            .height(110.dp)
            .clip(RoundedCornerShape(12.dp))
            .background(Brush.linearGradient(gradient))
            .clickable(onClick = onClick),
        contentAlignment = Alignment.Center
    ) {
        if (icon != null) {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Icon(icon, null, tint = Color.White, modifier = Modifier.size(22.dp))
                Spacer(Modifier.width(8.dp))
                Text(label, color = Color.White, style = AppleText.Title3.copy(fontWeight = FontWeight.Bold))
            }
        } else {
            Text(label, color = Color.White, style = AppleText.Title3.copy(fontWeight = FontWeight.Bold))
        }
    }
}

@Composable
private fun Section(title: String, content: androidx.compose.foundation.lazy.LazyListScope.() -> Unit) {
    Column {
        SectionHeader(title)
        LazyRow(
            contentPadding = PaddingValues(horizontal = 16.dp),
            horizontalArrangement = Arrangement.spacedBy(4.dp)
        ) {
            content()
        }
    }
}
