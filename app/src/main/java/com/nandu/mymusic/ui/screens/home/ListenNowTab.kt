package com.nandu.mymusic.ui.screens.home

import androidx.compose.foundation.background
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.foundation.lazy.LazyRow
import androidx.compose.foundation.lazy.items
import androidx.compose.runtime.Composable
import androidx.compose.runtime.remember
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp
import com.nandu.mymusic.model.Song
import com.nandu.mymusic.ui.screens.library.LargeTitleHeader
import com.nandu.mymusic.ui.screens.library.PlaylistShelfCard
import com.nandu.mymusic.ui.screens.library.SongShelfCard
import com.nandu.mymusic.ui.theme.LikedSongsGradient
import com.nandu.mymusic.ui.theme.appleColors

/**
 * Apple Music "Listen Now" tab — personalized horizontal shelves built from
 * the existing library data (no ViewModel changes).
 */
@Composable
fun ListenNowTab(
    songs: List<Song>,
    favorites: List<Song>,
    queue: List<Song>,
    currentSong: Song?,
    playlists: Map<String, List<Long>>,
    autoGeneratedPlaylists: Set<String>,
    onSongClick: (Song) -> Unit,
    onSongClickIn: (Song, List<Song>) -> Unit,
    onToggleFavorite: (Song) -> Unit,
    onOpenPlaylist: (String) -> Unit,
    onOpenLikedSongs: () -> Unit,
    onViewAlbum: (String) -> Unit,
    onViewArtist: (String) -> Unit
) {
    val C = appleColors()

    // Recently played = songs played before the current one in the queue (the only
    // history the ViewModel exposes).
    val recentlyPlayed = remember(queue, currentSong) {
        val idx = queue.indexOfFirst { it.id == currentSong?.id }
        if (idx > 0) queue.take(idx).reversed() else emptyList()
    }

    // Language playlists = auto-generated entries ("Made for You").
    val madeForYou = remember(playlists, autoGeneratedPlaylists) {
        playlists.entries.filter { autoGeneratedPlaylists.contains(it.key) }
            .sortedBy { when (it.key) { "Telugu Songs" -> 0; "English Songs" -> 1; else -> 2 } }
    }

    LazyColumn(
        modifier = Modifier
            .fillMaxSize()
            .background(C.background)
            .statusBarsPadding(),
        contentPadding = PaddingValues(bottom = 24.dp)
    ) {
        item { LargeTitleHeader("Listen Now") }

        // ── Top Picks ──
        if (songs.isNotEmpty()) {
            item {
                Section("Top Picks") {
                    items(songs.take(8), key = { "top_${it.id}" }) { song ->
                        SongShelfCard(song = song, onClick = { onSongClick(song) })
                    }
                }
            }
        }

        // ── Made for You (language playlists) ──
        if (madeForYou.isNotEmpty()) {
            item {
                Section("Made for You") {
                    items(madeForYou, key = { "mfy_${it.key}" }) { (name, ids) ->
                        PlaylistShelfCard(
                            name = name,
                            songCount = ids.size,
                            gradient = LikedSongsGradient,
                            icon = null,
                            onClick = { onOpenPlaylist(name) }
                        )
                    }
                }
            }
        }

        // ── Recently Played ──
        if (recentlyPlayed.isNotEmpty()) {
            item {
                Section("Recently Played") {
                    items(recentlyPlayed.take(12), key = { "rp_${it.id}" }) { song ->
                        SongShelfCard(song = song, onClick = { onSongClick(song) })
                    }
                }
            }
        }

        // ── Top Songs (favorites) ──
        if (favorites.isNotEmpty()) {
            item {
                Section("Top Songs") {
                    items(favorites.take(12), key = { "fav_${it.id}" }) { song ->
                        SongShelfCard(song = song, onClick = { onSongClickIn(song, favorites) })
                    }
                }
            }
        }
    }
}

@Composable
private fun Section(title: String, content: androidx.compose.foundation.lazy.LazyListScope.() -> Unit) {
    Column {
        com.nandu.mymusic.ui.screens.library.SectionHeader(title)
        LazyRow(
            contentPadding = PaddingValues(horizontal = 16.dp),
            horizontalArrangement = Arrangement.spacedBy(4.dp)
        ) {
            content()
        }
    }
}
