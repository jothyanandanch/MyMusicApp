private const val TOP_PICKS_COUNT = 8

/**
 * Apple Music "Listen Now" tab — personalized horizontal shelves built from
 * the existing library data (no ViewModel changes).
 */
@Composable
fun ListenNowTab(
    songs: List<Song>,
    favorites: List<Song>,
    queue: List<Song>,
    playHistory: List<Song>,
    currentSong: Song?,
    playlists: Map<String, List<Long>>,
    autoGeneratedPlaylists: Set<String>,
    rotationSeed: Int,
    onSongClick: (Song) -> Unit,
    onSongClickIn: (Song, List<Song>) -> Unit,
    onToggleFavorite: (Song) -> Unit,
    onOpenPlaylist: (String) -> Unit,
    onOpenLikedSongs: () -> Unit,
    onViewAlbum: (String) -> Unit,
    onViewArtist: (String) -> Unit
) {
    val C = appleColors()

    // Recently Played — persistent play history from the ViewModel (survives
    // app restarts, like Apple Music). Falls back to queue history while the
    // persisted history is still empty this session.
    val recentlyPlayed = if (playHistory.isNotEmpty()) playHistory else {
        remember(queue, currentSong) {
            val idx = queue.indexOfFirst { it.id == currentSong?.id }
            if (idx > 0) queue.take(idx).reversed() else emptyList()
        }
    }

    // Top Picks: curated like Apple Music — favorites and listening history,
    // rotated with a per-session seed so the shelf refreshes on each app launch
    // but stays stable while you use it.
    val topPicks = remember(songs, favorites, rotationSeed) {
        buildTopPicks(
            library = songs,
            favorites = favorites,
            recentlyPlayed = recentlyPlayed,
            currentSongId = currentSong?.id,
            seed = rotationSeed
        )
    }

    // Made for You: personalized mixes first, then language playlists. Covers are
    // Apple-style 2×2 mosaics of each playlist's first four tracks.
    val madeForYou = remember(playlists, autoGeneratedPlaylists) {
        playlists.entries.filter { autoGeneratedPlaylists.contains(it.key) }
            .sortedBy { when (it.key) {
                "Favorites Mix" -> -2; "Replay" -> -1
                "Telugu Songs" -> 0; "English Songs" -> 1; else -> 2 } }
    }
    val playlistCovers = remember(playlists, songs) {
        playlists.mapValues { (_, ids) -> songs.filter { ids.contains(it.id) }.take(4) }
    }

    LazyColumn(
        modifier = Modifier
            .fillMaxSize()
            .background(C.background)
            .statusBarsPadding(),
        contentPadding = PaddingValues(bottom = 24.dp)
    ) {
        item { LargeTitleHeader("Listen Now") }

        // ── Top Picks ──
        if (topPicks.isNotEmpty()) {
            item {
                Section("Top Picks") {
                    items(topPicks, key = { "top_${it.id}" }) { song ->
                        SongShelfCard(song = song, onClick = { onSongClick(song) })
                    }
                }
            }
        }

        // ── Made for You (personalized mixes + language playlists) ──
        if (madeForYou.isNotEmpty()) {
            item {
                Section("Made for You") {
                    items(madeForYou, key = { "mfy_${it.key}" }) { (name, ids) ->
                        PlaylistShelfCard(
                            name = name,
                            songCount = ids.size,
                            coverSongs = playlistCovers[name] ?: emptyList(),
                            gradient = LikedSongsGradient,
                            icon = when (name) {
                                "Favorites Mix" -> Icons.Filled.Favorite
                                "Replay" -> Icons.Filled.Whatshot
                                else -> null
                            },
                            onClick = { onOpenPlaylist(name) }
                        )
                    }
                }
            }
        }

        // ── Recently Played ──
        if (recentlyPlayed.isNotEmpty()) {
            item {
                Section("Recently Played") {
                    items(recentlyPlayed.take(12), key = { "rp_${it.id}" }) { song ->
                        SongShelfCard(song = song, onClick = { onSongClick(song) })
                    }
                }
            }
        }

        // ── Top Songs (favorites) ──
        if (favorites.isNotEmpty()) {
            item {
                Section("Top Songs") {
                    items(favorites.take(12), key = { "fav_${it.id}" }) { song ->
                        SongShelfCard(song = song, onClick = { onSongClickIn(song, favorites) })
                    }
                }
            }
        }
    }
}

@Composable
private fun Section(title: String, content: androidx.compose.foundation.lazy.LazyListScope.() -> Unit) {
    Column {
        com.nandu.mymusic.ui.screens.library.SectionHeader(title)
        LazyRow(
            contentPadding = PaddingValues(horizontal = 16.dp),
            horizontalArrangement = Arrangement.spacedBy(4.dp)
        ) {
            content()
        }
    }
}

/**
 * Curates the "Top Picks" shelf Apple Music style:
 * 1. Half the slots go to favorites (seed-shuffled),
 * 2. A third go to recently played (most recent first, excluding already-picked),
 * 3. Remaining slots are filled with seed-shuffled library songs for variety.
 * If the personal pools are thin, the shelf gracefully degrades to library picks.
 * The [seed] rotates the selection per app session; it stays stable in-session.
 */
private fun buildTopPicks(
    library: List<Song>,
    favorites: List<Song>,
    recentlyPlayed: List<Song>,
    currentSongId: Long?,
    seed: Int
): List<Song> {
    val random = Random(seed)
    val picked = ArrayList<Song>(TOP_PICKS_COUNT)
    val pickedIds = HashSet<Long>()

    val favPool = favorites.shuffled(random).filter { it.id != currentSongId }
    val libraryPool = library.filter { it.id != currentSongId }.shuffled(random)

    // 1. Favorites — up to half the shelf, shuffled
    pickedIds.addAll(favPool.take(TOP_PICKS_COUNT / 2).map { it.id })
    picked.addAll(favPool.take(TOP_PICKS_COUNT / 2))

    // 2. Recently played — about a third, most recent first
    val rpSlots = TOP_PICKS_COUNT / 3
    val rpCandidates = recentlyPlayed
        .filter { it.id != currentSongId && pickedIds.add(it.id) }
        .take(rpSlots)
    picked.addAll(rpCandidates)

    // 3. Fill remaining slots from the shuffled library
    val filler = libraryPool.filter { pickedIds.add(it.id) }
    picked.addAll(filler)

    // Interleave so favorites don't all cluster at the front
    return picked.distinctBy { it.id }.take(TOP_PICKS_COUNT).shuffled(random)
}
